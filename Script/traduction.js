function appliquerTraduction(lang) {
  const traduct = traductions[lang];
  if (!traduct) return;

  document.querySelectorAll("[data-i18n]").forEach((el) => {
    const key = el.getAttribute("data-i18n");
    if (traduct[key]) el.textContent = traduct[key];
  });

  document.querySelectorAll("[data-i18n-placeholder]").forEach((el) => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (traduct[key]) el.placeholder = traduct[key];
  });

  document.documentElement.lang = lang;
  localStorage.setItem("lang", lang);
}

// Chargement
const savedLang = localStorage.getItem("lang") || "fr";
appliquerTraduction(savedLang);

// Sélecteur (présent sur toutes les pages)
const langSelect = document.getElementById("lang-select");
if (langSelect) {
  langSelect.value = savedLang;
  langSelect.addEventListener("change", (e) => {
    appliquerTraduction(e.target.value);
  });
}
