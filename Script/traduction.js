function appliquerTraduction(lang) {
  const traduct = traductions[lang];
  if (!traduct) return;

  // Textes simples
  document.querySelectorAll("[data-i18n]").forEach(el => {
    const key = el.getAttribute("data-i18n");
    if (traduct[key]) el.textContent = traduct[key];
  });

  // Placeholder
  document.querySelectorAll("[data-i18n-placeholder]").forEach(el => {
    const key = el.getAttribute("data-i18n-placeholder");
    if (traduct[key]) el.placeholder = traduct[key];
  });

  document.documentElement.lang = lang;
  localStorage.setItem("lang", lang);
}

// Au chargement de la page 
const savedLang = localStorage.getItem("lang") || "fr";
document.getElementById("lang-select").value = savedLang;
appliquerTraduction(savedLang);

// Au changement de la langue
document.getElementById("lang-select").addEventListener("change", e => {
  appliquerTraduction(e.target.value);
});